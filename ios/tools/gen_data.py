"""Generate ios/MochiArcade/Engine/GeneratedData.swift from the Python sources, so the iOS port uses
exactly the same font, sprites, music, levels and game metadata as the desktop version.

usage: python ios/tools/gen_data.py   (run from the repository root, needs pygame importable)
"""
import os
import sys

ROOT = os.path.join(os.path.dirname(__file__), "..", "..")
sys.path.insert(0, ROOT)
os.environ.setdefault("PYGAME_HIDE_SUPPORT_PROMPT", "1")

from mochi_arcade import gfx, music, sprites  # noqa: E402
from mochi_arcade.games import GAMES, bounce_bun, jelly_stack, noodle_slurp, soap_hop  # noqa: E402


def sw(s):
    return '"' + str(s).replace("\\", "\\\\").replace('"', '\\"') + '"'


def arr(items, indent="    "):
    return "[" + ", ".join(items) + "]"


out = ["// GENERATED by ios/tools/gen_data.py from the Python sources - do not edit by hand.", "", "enum GData {"]

# palette
out.append("    static let palette: [String: (Int, Int, Int)] = [")
for k, (r, g, b) in gfx.PAL.items():
    out.append(f"        {sw(k)}: ({r}, {g}, {b}),")
out.append("    ]")
out.append("    static let spriteChars: [Character: String] = [")
for k, v in gfx.CHARS.items():
    out.append(f"        {sw(k)}: {sw(v)},")
out.append("    ]")

# font
out.append("    static let font: [Character: [String]] = [")
for k, rows in gfx.FONT.items():
    out.append(f"        {sw(k)}: {arr([sw(r) for r in rows])},")
out.append("    ]")

# sprites
out.append("    static let art: [String: [[String]]] = [")
for k, frames in sprites.ART.items():
    out.append(f"        {sw(k)}: [")
    for f in frames:
        out.append("            " + arr([sw(r) for r in f]) + ",")
    out.append("        ],")
out.append("    ]")

# music
out.append("    struct Channel { let wave: String; let vol: Double; let duty: Double; let decay: Double; let gate: Double; let vibrato: Double; let notes: String }")
out.append("    struct Song { let bpm: Double; let gain: Double; let channels: [Channel] }")
out.append("    static let songs: [String: Song] = [")
for name, s in music.SONGS.items():
    chans = []
    for c in s["channels"]:
        chans.append(f"Channel(wave: {sw(c['wave'])}, vol: {float(c.get('vol', 1))}, duty: {float(c.get('duty', 0.25))}, "
                     f"decay: {float(c.get('decay', 0.35))}, gate: {float(c.get('gate', 0.85))}, vibrato: {float(c.get('vibrato', 0.0))}, "
                     f"notes: {sw(' '.join(c['notes'].split()))})")
    out.append(f"        {sw(name)}: Song(bpm: {float(s['bpm'])}, gain: {float(s.get('gain', 0.8))}, channels: [")
    for ch in chans:
        out.append(f"            {ch},")
    out.append("        ]),")
out.append("    ]")

# soap hop levels (built 40x23 maps) and themes
out.append("    struct SoapLevel { let name: String; let map: [String] }")
out.append("    static let soapLevels: [SoapLevel] = [")
for lv in soap_hop.LEVELS:
    out.append(f"        SoapLevel(name: {sw(lv['name'])}, map: {arr([sw(r) for r in soap_hop.build(lv)])}),")
out.append("    ]")
out.append("    static let soapThemes: [[String]] = " + arr([arr([sw(x) for x in t]) for t in soap_hop.THEMES]))

# bounce bun levels
out.append("    static let bounceLevels: [(String, [String])] = [")
for name, rows in bounce_bun.LEVELS:
    out.append(f"        ({sw(name)}, {arr([sw(r) for r in rows])}),")
out.append("    ]")

# jelly stack rotations / kicks / colours
out.append("    static let jellyKinds: [String] = " + arr([sw(k) for k in jelly_stack.SHAPES]))
out.append("    static let jellyColors: [String: String] = [" + ", ".join(f"{sw(k)}: {sw(v)}" for k, v in jelly_stack.COLORS.items()) + "]")
out.append("    static let jellyRot: [String: [[(Int, Int)]]] = [")
for k, rots in jelly_stack.ROT.items():
    out.append(f"        {sw(k)}: {arr([arr([f'({x}, {y})' for x, y in r]) for r in rots])},")
out.append("    ]")
for nm, table in (("jellyKicks", jelly_stack.KICKS), ("jellyKicksI", jelly_stack.KICKS_I)):
    out.append(f"    static let {nm}: [Int: [(Int, Int)]] = [")
    for (a, b), v in table.items():
        out.append(f"        {a * 10 + b}: {arr([f'({x}, {y})' for x, y in v])},")
    out.append("    ]")

# games registry
out.append("    struct Option { let key: String; let label: String; let choices: [(String, String)]; let def: String }")
out.append("    struct Game { let id: String; let title: String; let tagline: String; let bg: String; let howto: [String]; let options: [Option] }")
out.append("    static let games: [Game] = [")
for g in GAMES:
    opts = []
    for key, label, choices, default in g.options:
        ch = arr([f"({sw(str(v).lower() if isinstance(v, bool) else v)}, {sw(l)})" for v, l in choices])
        d = str(default).lower() if isinstance(default, bool) else default
        opts.append(f"Option(key: {sw(key)}, label: {sw(label)}, choices: {ch}, def: {sw(d)})")
    out.append(f"        Game(id: {sw(g.id)}, title: {sw(g.title)}, tagline: {sw(g.tagline)}, bg: {sw(g.bg)}, "
               f"howto: {arr([sw(h) for h in g.howto])}, options: {arr(opts)}),")
out.append("    ]")
out.append("}")

path = os.path.join(ROOT, "ios", "MochiArcade", "Engine", "GeneratedData.swift")
with open(path, "w") as f:
    f.write("\n".join(out) + "\n")
print("wrote", path, sum(1 for _ in open(path)), "lines")
